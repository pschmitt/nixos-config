get_hostname() {
  local system_hostname
  system_hostname="$(hostname)"

  if [[ "$system_hostname" != "localhost" ]]
  then
    echo "$system_hostname"
    return
  fi

  # Use HOST var if set
  if [[ -n "$HOST" ]]
  then
    echo "$HOST"
    return 0
  fi

  # Use getprop on Termux
  if command -v termux-info >/dev/null
  then
    getprop net.hostname
    return
  fi

  # Default
  echo "$system_hostname"
}

status_left() {
  local halias
  local hcolor
  local scolor
  local session
  local shide

  # TMUX session
  local sname="$1"
  case "$sname" in
    main)
      shide=1
      ;;
    bg)
      scolor="#6c7570"
      ;;
    scratchpad)
      sname="📔"
      scolor="#035728"
      ;;
    *)
      scolor=red
      ;;
  esac

  # Hostname
  local host_name
  host_name="$(get_hostname)"

  # host_color and host_alias, generated by Home Manager
  local host_file="${XDG_CONFIG_HOME:-$HOME/.config}/tmux/host.sh"
  if [[ -r "$host_file" ]]
  then
    # shellcheck disable=1090
    source "$host_file"
  fi

  halias="${host_alias:-${host_name}}"

  # 256-color indices need tmux's colourN; names and #rrggbb work as is.
  # shellcheck disable=2154
  case "$host_color" in
    "")
      hcolor=red
      ;;
    *[!0-9]*)
      hcolor="$host_color"
      ;;
    *)
      hcolor="colour${host_color}"
      ;;
  esac

  # TMUX session
  if [[ "$shide" != "1" ]]
  then
    session="#[fg=${scolor},bold]${sname} "
  fi

  # Hostname
  echo -n " $session#[fg=${hcolor}]"
  echo -n "$halias"
  echo " "
}

system_load() {
  uptime | sed -r 's/.*load average: (.+), (.+), (.+)/\1 \2 \3/; s/,/./g'
}

status_right() {
  local load

  load="$(system_load)"

  echo "${load}"

  # FIXME %H:%M:%S etc won't be expanded
  # echo "#[fg=red]Not implemented yet %H:%M:%S"
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]
then
  set -e

  case "$1" in
    --left|-l|left|L|-L)
      shift
      status_left "$*"
      ;;
    --right|-r|right|R|-R)
      shift
      status_right "$1"
      ;;
  esac
fi
