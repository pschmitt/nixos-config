#!/usr/bin/env python3
"""Generate zsh code for programs.zsh.localConfig.prefixAliases.

Usage: prefix-aliases.py SPEC.json FUNCTION-NAMES PLUGIN...

SPEC.json is a list of {from, to, kind, env}. For every known function or
alias name that starts with `from`, emit `alias TO...=NAME` (kind "alias") or
a wrapper function `TO...() { [ENV] NAME "$@" }` (kind "function"; skipped
when that name is already defined). Known names are the autoloaded function
files (FUNCTION-NAMES, one per line), the functions and aliases the
plugins define and the names earlier entries generated.
"""
import json
import re
import shlex
import sys

FUNCTION_DEF = re.compile(r'^\s*(?:function\s+)?([^\s(){}=;|&<>\'"$]+)\s*\(\)')
FUNCTION_KEYWORD = re.compile(r'^\s*function\s+([^\s(){};]+)')
ALIAS_DEF = re.compile(r'^\s*alias\s+(?:-[a-zA-Z]+\s+)*(?:--\s+)?([^\s=\'"]+)=')


def plugin_names(path):
    functions, aliases = set(), set()
    with open(path, errors='replace') as handle:
        for line in handle:
            for pattern in (FUNCTION_DEF, FUNCTION_KEYWORD):
                match = pattern.match(line)
                if match:
                    functions.add(match.group(1))
            match = ALIAS_DEF.match(line)
            if match:
                aliases.add(match.group(1))
    return functions, aliases


def main(argv):
    if len(argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    with open(argv[1]) as handle:
        spec = json.load(handle)
    with open(argv[2]) as handle:
        functions = {line.strip() for line in handle if line.strip()}
    aliases = set()
    for path in argv[3:]:
        plugin_functions, plugin_aliases = plugin_names(path)
        functions |= plugin_functions
        aliases |= plugin_aliases
    out = ['# Generated by prefix-aliases.py from programs.zsh.localConfig.prefixAliases']
    # Entries run in order: names an entry generates are known to later ones.
    for entry in spec:
        source, target = entry['from'], entry['to']
        env = entry.get('env') or ''
        for name in sorted(functions | aliases):
            if not name.startswith(source):
                continue
            new = target + name[len(source):]
            if entry['kind'] == 'alias':
                out.append(f'alias -- {shlex.quote(new + "=" + name)}')
                aliases.add(new)
            elif new not in functions:
                command = f'{env} {shlex.quote(name)}' if env else shlex.quote(name)
                out.append(f'{shlex.quote(new)}() {{ {command} "$@"; }}')
                functions.add(new)
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
